function gone(request) {
  return new Response(request.method === 'HEAD' ? null : gonePage, {
    status: 410,
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'X-Robots-Tag': 'noindex',
      'Cache-Control': 'public, max-age=3600',
    },
  });
}

export function onRequest({ request, next }) {
  if (!['GET', 'HEAD'].includes(request.method)) return next();
  const url = new URL(request.url);
  // Retired PHP endpoints only; never match the static directory or current API.
  if (/^\/(?:static|yineng)\/index\.php(?:\/|$)/.test(url.pathname)
    || /^\/api\.php(?:\/|$)/.test(url.pathname)
    || /^\/core\/code\.php(?:\/|$)/.test(url.pathname)) return gone(request);

  if (url.pathname !== '/') return next();
  // URLSearchParams handles both ?pro1/151.html and ?pro1%2F151.html=.
  for (const [key] of url.searchParams) {
    const target = legacyRedirects.get(key);
    if (target) return new Response(null, {
      status: 301,
      headers: {
        Location: `https://fahint.com${target}`,
        'Cache-Control': 'public, max-age=3600',
      },
    });
  }
  // Old CMS routes without an equivalent are retired, not homepage aliases.
  if ([...url.searchParams.keys()].some(key => /^(?:pro\d+|list_\d+)\/(?:\d+\.html)?$/.test(key))
    || url.searchParams.get('p') === '/Do/area') return gone(request);
  return next();
}
